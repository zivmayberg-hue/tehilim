// Generates the weekly-portion table embedded in index.html (between the PARSHA_TABLE markers),
// from @hebcal/core 5.8.0, for every Saturday from FIRST to the end of LAST_YEAR, diaspora and Israel.
// Usage: NODE_PATH=tests/node_modules node tests/gen-parsha-table.js
// Russian names are the same as in notify/notify.js.
"use strict";
const fs = require("fs");
const path = require("path");
const H = require("@hebcal/core");

const FIRST = [2026, 0, 3], LAST_YEAR = 2036;          // the first Saturday of 2026
const RU = {
  "Bereshit":"Берешит","Noach":"Ноах","Lech-Lecha":"Лех Леха","Vayera":"Вайера","Chayei Sara":"Хаей Сара","Toldot":"Толдот",
  "Vayetzei":"Вайеце","Vayishlach":"Вайишлах","Vayeshev":"Вайешев","Miketz":"Микец","Vayigash":"Ваигаш","Vayechi":"Вайехи",
  "Shemot":"Шмот","Vaera":"Ваэра","Bo":"Бо","Beshalach":"Бешалах","Yitro":"Итро","Mishpatim":"Мишпатим","Terumah":"Трума",
  "Tetzaveh":"Тецаве","Ki Tisa":"Ки Тиса","Vayakhel":"Ваякгель","Pekudei":"Пкудей","Vayikra":"Ваикра","Tzav":"Цав",
  "Shmini":"Шмини","Tazria":"Тазриа","Metzora":"Мецора","Achrei Mot":"Ахарей Мот","Kedoshim":"Кдошим","Emor":"Эмор",
  "Behar":"Беар","Bechukotai":"Бехукотай","Bamidbar":"Бамидбар","Nasso":"Насо","Beha'alotcha":"Беаалотха","Sh'lach":"Шлах",
  "Korach":"Корах","Chukat":"Хукат","Balak":"Балак","Pinchas":"Пинхас","Matot":"Матот","Masei":"Масэй","Devarim":"Дварим",
  "Vaetchanan":"Ваэтханан","Eikev":"Экев","Re'eh":"Ре'э","Shoftim":"Шофтим","Ki Teitzei":"Ки Теце","Ki Tavo":"Ки Таво",
  "Nitzavim":"Ницавим","Vayeilech":"Вайелех","Ha'azinu":"Аазину",
};
const CANTILLATION = /[֑-֯]/g;

function build() {
  const names = H.parshiot.map(p => [RU[p], H.Locale.gettext(p, "he").replace(CANTILLATION, "")]);
  if (names.some(([ru]) => !ru)) throw new Error("missing Russian name");
  const token = l => l.chag ? "" : l.parsha.map(p => H.parshiot.indexOf(p)).join("+");
  const dia = [], il = [];
  for (let d = new Date(...FIRST); d.getFullYear() <= LAST_YEAR; d = new Date(d.getFullYear(), d.getMonth(), d.getDate() + 7)) {
    const hd = new H.HDate(d), y = hd.getFullYear();
    dia.push(token(H.getSedra(y, false).lookup(hd)));
    il.push(token(H.getSedra(y, true).lookup(hd)));
  }
  const first = `${FIRST[0]}-${String(FIRST[1] + 1).padStart(2, "0")}-${String(FIRST[2]).padStart(2, "0")}`;
  return `/* PARSHA_TABLE:BEGIN generated by tests/gen-parsha-table.js from @hebcal/core ${H.version}, do not edit by hand.
   Every Saturday from ${first}: index into PARSHA_NAMES, "a+b" for joined portions, empty for a holiday reading. */
const PARSHA_NAMES = ${JSON.stringify(names)};
const PARSHA_TABLE = {first:"${first}", weeks:${dia.length},
  dia:"${dia.join(",")}",
  il:"${il.join(",")}"};
/* PARSHA_TABLE:END */`;
}

module.exports = { build };
if (require.main === module) {
  const file = path.join(__dirname, "..", "index.html");
  const html = fs.readFileSync(file, "utf8");
  const re = /\/\* PARSHA_TABLE:BEGIN[\s\S]*?\/\* PARSHA_TABLE:END \*\//;
  if (!re.test(html)) throw new Error("PARSHA_TABLE markers not found in index.html");
  fs.writeFileSync(file, html.replace(re, () => build()));
  console.log("index.html: portion table updated");
}
